List<Map<String, dynamic>> _generateVocabQuiz(
    List<Map<String, String>> vocabList, String type) {
  // Get all meanings for wrong answer options
  List<String> allMeanings = [];

  switch (type) {
    case 'nouns':
      allMeanings = n5Nouns.map((e) => e['meaning']!).toList();
      break;
    case 'verbs':
      allMeanings = n5Verbs.map((e) => e['meaning']!).toList();
      break;
    case 'iAdj':
      allMeanings = n5iAdjectives.map((e) => e['meaning']!).toList();
      break;
    case 'naAdj':
      allMeanings = n5NaAdjectives.map((e) => e['meaning']!).toList();
      break;
    case 'Adv':
      allMeanings = n5Adverbs.map((e) => e['meaning']!).toList();
      break;
    case 'Particles':
      allMeanings = n5Particles.map((e) => e['meaning']!).toList();
      break;
    default:
      allMeanings = vocabList.map((e) => e['meaning']!).toList();
  }

  List<Map<String, dynamic>> quiz = [];

  for (var vocab in vocabList) {
    String correct = vocab['meaning']!;

    // Get the display word (kanji if available, otherwise nihongo)
    String displayWord;
    if (type == 'nouns') {
      displayWord = vocab['kanji']?.isNotEmpty == true
          ? vocab['kanji']!
          : vocab['nihongo']!;
    } else if (type == 'verbs') {
      displayWord = vocab['dictionary']!;
    } else {
      displayWord = vocab['Nihongo']!;
    }

    String reading = vocab['reading']!;

    // Pick 3 random distractors excluding the correct answer
    List<String> distractors = [];
    List<String> tempMeanings = List.from(allMeanings)..remove(correct);

    while (distractors.length < 3 && tempMeanings.isNotEmpty) {
      String choice = tempMeanings[_random.nextInt(tempMeanings.length)];
      if (!distractors.contains(choice)) {
        distractors.add(choice);
        tempMeanings.remove(choice);
      }
    }

    // Ensure we have at least 2 options
    List<String> options = List.from(distractors)..add(correct);
    if (options.length < 2) {
      // Add some generic options if we don't have enough
      List<String> fallbackOptions = ['thing', 'word', 'item', 'concept'];
      while (options.length < 4) {
        options.add(fallbackOptions[options.length - 1]);
      }
    }

    options.shuffle(_random);

    quiz.add({
      'word': displayWord,
      'reading': reading,
      'answer': correct,
      'options': options,
      'type': _getTypeName(type),
    });
  }

  return quiz..shuffle(_random);
}

String _getTypeName(String type) {
  switch (type) {
    case 'nouns':
      return 'Noun';
    case 'verbs':
      return 'Verb';
    case 'iAdj':
      return 'i-Adjective';
    case 'naAdj':
      return 'na-Adjective';
    case 'Adv':
      return 'Adverb';
    case 'Particles':
      return 'Particle';
    default:
      return 'Vocabulary';
  }
}
